import os
import subprocess
from pathlib import Path

from conftest import write

from tutorial_ai.repository.scanner import FileCategory, scan_repository


def _by_path(root: Path, max_file_bytes: int = 200_000):
    scan = scan_repository(root, max_file_bytes)
    return scan, {f.path: f for f in scan.files}


def test_ignored_directories_are_pruned(sample_repo: Path):
    scan, files = _by_path(sample_repo)
    assert not any(p.startswith(("node_modules/", ".venv/", "dist/")) for p in files)
    assert {"node_modules/", ".venv/", "dist/"} <= set(scan.ignored_directories)


def test_useful_files_are_allowed(sample_repo: Path):
    _, files = _by_path(sample_repo)
    for path in ["README.md", "pyproject.toml", "app/main.py", "app/routes/items.py", ".env.example"]:
        assert files[path].content_allowed, path


def test_skip_reasons(sample_repo: Path):
    _, files = _by_path(sample_repo)
    assert files[".env"].skip_reason == "may contain secrets"
    assert files["uv.lock"].skip_reason == "lockfile"
    assert files["static/logo.png"].skip_reason == "binary or media file"
    assert files["data/big.csv"].skip_reason == "large data file"
    assert files["app/vendor.min.js"].skip_reason == "generated file"
    assert files["blob.dat"].skip_reason == "binary content"


def test_categories(sample_repo: Path):
    _, files = _by_path(sample_repo)
    assert files["app/main.py"].category is FileCategory.SOURCE
    assert files["app/main.py"].language == "Python"
    assert files["tests/test_main.py"].category is FileCategory.TEST
    assert files["pyproject.toml"].category is FileCategory.MANIFEST
    assert files["README.md"].category is FileCategory.DOCS
    assert files["uv.lock"].category is FileCategory.LOCKFILE


def test_large_files_are_not_sent(tmp_path: Path):
    write(tmp_path, "big.py", "x = 1\n" * 1000)
    _, files = _by_path(tmp_path, max_file_bytes=1_000)
    assert files["big.py"].skip_reason.startswith("too large")


def test_git_repository_respects_gitignore(sample_repo: Path):
    write(sample_repo, ".gitignore", "secret_notes.txt\n")
    write(sample_repo, "secret_notes.txt", "do not send\n")
    subprocess.run(["git", "init", "-q", str(sample_repo)], check=True)
    _, files = _by_path(sample_repo)
    assert "secret_notes.txt" not in files
    assert "app/main.py" in files
    assert not any(p.startswith(".git/") for p in files)


def test_symlinks_are_not_followed(tmp_path: Path):
    outside = write(tmp_path / "outside", "passwords.txt", "hunter2\n")
    root = tmp_path / "repo"
    write(root, "main.py", "print(1)\n")
    (root / "link.txt").symlink_to(outside)
    _, files = _by_path(root)
    assert "link.txt" not in files


def test_generated_files_detected_by_suffix_and_header(tmp_path: Path):
    write(tmp_path, "src/client/sdk.gen.ts", "export const a = 1\n")
    write(tmp_path, "api/types.go", "// Code generated by protoc. DO NOT EDIT.\npackage api\n")
    write(tmp_path, "src/app.ts", "// Handwritten. Edit freely.\nexport const b = 2\n")
    _, files = _by_path(tmp_path)
    assert files["src/client/sdk.gen.ts"].skip_reason == "generated file"
    assert files["api/types.go"].skip_reason == "generated file"
    assert files["src/app.ts"].content_allowed


def test_directory_walk_does_not_descend_into_ignored_dirs(tmp_path: Path, monkeypatch):
    write(tmp_path, "main.py", "x = 1\n")
    write(tmp_path, "node_modules/pkg/deep/index.js", "x\n")
    walked: list[str] = []
    real_walk = os.walk

    def spy(*args, **kwargs):
        for entry in real_walk(*args, **kwargs):
            walked.append(entry[0])
            yield entry

    monkeypatch.setattr(os, "walk", spy)
    scan, files = _by_path(tmp_path)
    assert list(files) == ["main.py"]
    assert scan.ignored_directories == ["node_modules/"]
    assert not any("node_modules" in d for d in walked)
