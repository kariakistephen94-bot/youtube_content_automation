class FileCategory(StrEnum):
    SOURCE = "source"
    TEST = "test"
    MANIFEST = "manifest"
    CONFIG = "config"
    DOCS = "docs"
    LOCKFILE = "lockfile"
    DATA = "data"
    OTHER = "other"


class ScannedFile(BaseModel):
    path: str  # POSIX, relative to the repository root
    size_bytes: int
    category: FileCategory
    language: str | None = None
    skip_reason: str | None = None  # set when the content must not be sent to the AI

    @property
    def content_allowed(self) -> bool:
        return self.skip_reason is None


class ScanResult(BaseModel):
    root: Path
    files: list[ScannedFile]
    ignored_directories: list[str]

    @property
    def paths(self) -> set[str]:
        return {f.path for f in self.files}

    def get(self, path: str) -> ScannedFile | None:
        return next((f for f in self.files if f.path == path), None)


def scan_repository(root: Path, max_file_bytes: int) -> ScanResult:
    root = root.resolve()
    relative_paths, ignored_dirs = _list_files(root)
    files: list[ScannedFile] = []
    for rel in sorted(relative_paths):
        full = root / rel
        if full.is_symlink() or not full.is_file():
            continue
        files.append(classify_file(rel, full, max_file_bytes))

    log.info(
        "Scanned %s: %d files, %d with content allowed, %d ignored directories",
        root, len(files), sum(f.content_allowed for f in files), len(ignored_dirs),
    )
    return ScanResult(root=root, files=files, ignored_directories=sorted(ignored_dirs))


def _is_ignored_dir(name: str) -> bool:
    return name in IGNORED_DIRS or name.endswith(".egg-info")


def _list_files(root: Path) -> tuple[list[str], set[str]]:
    """Prefer `git ls-files` (respects .gitignore); fall back to a pruned directory walk."""
    kept: list[str] = []
    ignored_dirs: set[str] = set()

    candidates = _git_ls_files(root)
    if candidates is None:
        candidates = []
        for dirpath, dirnames, filenames in os.walk(root, followlinks=False):
            current = Path(dirpath)
            keep_dirs = []
            for d in sorted(dirnames):
                if _is_ignored_dir(d):  # prune: never descend into node_modules, .venv, ...
                    ignored_dirs.add((current / d).relative_to(root).as_posix() + "/")
                elif not (current / d).is_symlink():
                    keep_dirs.append(d)
            dirnames[:] = keep_dirs
            for name in filenames:
                candidates.append((current / name).relative_to(root).as_posix())

    for rel in candidates:
        parts = PurePosixPath(rel).parts
        ignored_index = next((i for i, part in enumerate(parts[:-1]) if _is_ignored_dir(part)), None)
        if ignored_index is None:
            kept.append(rel)
        else:
            ignored_dirs.add("/".join(parts[: ignored_index + 1]) + "/")
    return kept, ignored_dirs


def _git_ls_files(root: Path) -> list[str] | None:
    if not (root / ".git").exists():
        return None
    try:
        result = subprocess.run(
            ["git", "-C", str(root), "ls-files", "-z", "--cached", "--others", "--exclude-standard"],
            capture_output=True,
            timeout=60,
            check=False,
        )
    except (FileNotFoundError, subprocess.TimeoutExpired):
        return None
    if result.returncode != 0:
        return None
    return [p for p in result.stdout.decode("utf-8", "replace").split("\0") if p]


def classify_file(rel: str, full: Path, max_file_bytes: int) -> ScannedFile:
    path = PurePosixPath(rel)
    name = path.name
    lower = name.lower()
    suffix = path.suffix.lower()
    size = full.stat().st_size
    language = _language_for(name, suffix)
    category = _category_for(path, name, suffix, language)

    skip_reason: str | None = None
    if name in SECRET_NAMES or suffix in SECRET_EXTENSIONS or (
        lower.startswith(".env") and name not in MANIFESTS
    ):
        skip_reason = "may contain secrets"
    elif category is FileCategory.LOCKFILE:
        skip_reason = "lockfile"
    elif suffix in BINARY_EXTENSIONS:
        skip_reason = "binary or media file"
    elif lower.endswith(GENERATED_SUFFIXES):
        skip_reason = "generated file"
    elif category is FileCategory.DATA and size > MAX_DATA_FILE_BYTES:
        skip_reason = "large data file"
    elif size > max_file_bytes:
        skip_reason = f"too large ({size:,} bytes)"
    else:
        head = _read_head(full)
        if head is None or b"\0" in head:
            skip_reason = "binary content"
        elif category is not FileCategory.MANIFEST and _has_generated_marker(head):
            skip_reason = "generated file"

    return ScannedFile(
        path=rel, size_bytes=size, category=category, language=language, skip_reason=skip_reason
    )


def _language_for(name: str, suffix: str) -> str | None:
    if name == "Dockerfile" or name.startswith("Dockerfile."):
        return "Dockerfile"
    if name in {"Makefile", "justfile"}:
        return "Makefile"
    return LANGUAGES_BY_EXTENSION.get(suffix)


def _category_for(path: PurePosixPath, name: str, suffix: str, language: str | None) -> FileCategory:
    lower = name.lower()
    dirs = {part.lower() for part in path.parts[:-1]}
    if name in LOCKFILES:
        return FileCategory.LOCKFILE
    if name in MANIFESTS or (lower.startswith("requirements") and suffix in {".txt", ".in"}):
        return FileCategory.MANIFEST
    if suffix in DATA_EXTENSIONS:
        return FileCategory.DATA
    if (
        dirs & _TEST_DIRS
        or lower.startswith("test_")
        or path.stem.endswith(("_test", ".test", ".spec"))
        or lower == "conftest.py"
    ):
        return FileCategory.TEST
    if suffix in {".md", ".rst", ".txt"} or dirs & _DOC_DIRS:
        return FileCategory.DOCS
    if suffix in _CONFIG_EXTENSIONS or name.startswith("."):
        return FileCategory.CONFIG
    if language and language not in NON_PROGRAMMING_LANGUAGES:
        return FileCategory.SOURCE
    return FileCategory.OTHER


def _read_head(full: Path, size: int = 8192) -> bytes | None:
    try:
        with full.open("rb") as handle:
            return handle.read(size)
    except OSError:
        return None


def _has_generated_marker(head: bytes) -> bool:
    first_lines = b"\n".join(head.split(b"\n", 6)[:6]).lower()
    return any(marker in first_lines for marker in GENERATED_MARKERS)
